window.currentFilteredCCE = [...window.cceMembrosData];
let cceViewMode = 'cards'; // 'cards' ou 'table'

function renderCCEMembros() {
  setupCCEListeners();
  filterCCEMembros();
}

function setupCCEListeners() {
  const searchInput = document.getElementById('searchCCE');
  const selOrgao = document.getElementById('filterCCEOrgao');
  const selTipo = document.getElementById('filterCCETipo');
  const btnLimpar = document.getElementById('btnLimparFiltrosCCE');
  const btnExport = document.getElementById('btnExportCCE');
  const btnToggleCards = document.getElementById('btnCCEViewCards');
  const btnToggleTable = document.getElementById('btnCCEViewTable');

  if (searchInput && !searchInput.dataset.listening) {
    searchInput.dataset.listening = 'true';
    searchInput.addEventListener('input', filterCCEMembros);
  }
  if (selOrgao && !selOrgao.dataset.listening) {
    selOrgao.dataset.listening = 'true';
    selOrgao.addEventListener('change', filterCCEMembros);
  }
  if (selTipo && !selTipo.dataset.listening) {
    selTipo.dataset.listening = 'true';
    selTipo.addEventListener('change', filterCCEMembros);
  }
  if (btnLimpar && !btnLimpar.dataset.listening) {
    btnLimpar.dataset.listening = 'true';
    btnLimpar.addEventListener('click', limparFiltrosCCE);
  }
  if (btnExport && !btnExport.dataset.listening) {
    btnExport.dataset.listening = 'true';
    btnExport.addEventListener('click', exportarCCECSV);
  }

  if (btnToggleCards && !btnToggleCards.dataset.listening) {
    btnToggleCards.dataset.listening = 'true';
    btnToggleCards.addEventListener('click', () => {
      cceViewMode = 'cards';
      renderCCEMembrosView();
    });
  }

  if (btnToggleTable && !btnToggleTable.dataset.listening) {
    btnToggleTable.dataset.listening = 'true';
    btnToggleTable.addEventListener('click', () => {
      cceViewMode = 'table';
      renderCCEMembrosView();
    });
  }
}

function filterCCEMembros() {
  const searchVal = normStr(document.getElementById('searchCCE')?.value);
  const orgaoVal = normStr(document.getElementById('filterCCEOrgao')?.value);
  const tipoVal = (document.getElementById('filterCCETipo')?.value || '').toUpperCase();

  const filtered = window.cceMembrosData.filter(m => {
    // 1. Busca textual
    if (searchVal) {
      const nome = normStr(m.nome);
      const cargo = normStr(m.cargo);
      const email = normStr(m.email);
      const inst = normStr(m.instituicao);
      const orgao = normStr(m.orgao_grupo);
      if (!nome.includes(searchVal) && !cargo.includes(searchVal) && !email.includes(searchVal) && !inst.includes(searchVal) && !orgao.includes(searchVal)) {
        return false;
      }
    }

    // 2. Órgão / Grupo
    if (orgaoVal) {
      const orgao = normStr(m.orgao_grupo);
      if (!orgao.includes(orgaoVal)) return false;
    }

    // 3. Tipo (Titular / Suplente)
    if (tipoVal) {
      if (m.tipo !== tipoVal) return false;
    }

    return true;
  });

  window.currentFilteredCCE = filtered;

  const countBadge = document.getElementById('cceCountBadge');
  if (countBadge) {
    countBadge.textContent = `${filtered.length} de ${window.cceMembrosData.length} representantes`;
  }

  renderCCEMembrosView();
}

function limparFiltrosCCE() {
  const searchInput = document.getElementById('searchCCE');
  const selOrgao = document.getElementById('filterCCEOrgao');
  const selTipo = document.getElementById('filterCCETipo');

  if (searchInput) searchInput.value = '';
  if (selOrgao) selOrgao.value = '';
  if (selTipo) selTipo.value = '';

  filterCCEMembros();
}

function renderCCEMembrosView() {
  const containerCards = document.getElementById('cceCardsContainer');
  const containerTable = document.getElementById('cceTableContainer');
  const data = window.currentFilteredCCE || [];

  document.getElementById('btnCCEViewCards')?.classList.toggle('on', cceViewMode === 'cards');
  document.getElementById('btnCCEViewTable')?.classList.toggle('on', cceViewMode === 'table');

  if (cceViewMode === 'cards') {
    if (containerCards) containerCards.style.display = 'block';
    if (containerTable) containerTable.style.display = 'none';
    renderCCECards(data);
  } else {
    if (containerCards) containerCards.style.display = 'none';
    if (containerTable) containerTable.style.display = 'block';
    renderCCETable(data);
  }
}

function cceContact(m) {
  const cleanPhone = (m.telefone || '').replace(/\D/g, '');
  const firstPhone = cleanPhone.slice(0, 11);
  return `<div class="contact-line">
      <a href="mailto:${escapeHTML(m.email)}">${escapeHTML(m.email)}</a>
      <button class="icon-btn" title="Copiar e-mail" onclick="navigator.clipboard.writeText(decodeURIComponent('${encodeURIComponent(m.email)}')); showToast('E-mail copiado', 'success')"><i class="fas fa-copy"></i></button>
      <span class="muted">${escapeHTML(m.telefone || '')}</span>
      ${firstPhone ? `<a href="https://wa.me/55${firstPhone}" target="_blank" rel="noopener noreferrer" title="Conversar no WhatsApp"><i class="fab fa-whatsapp"></i> WhatsApp</a>` : ''}
    </div>`;
}

function renderCCECards(data) {
  const container = document.getElementById('cceCardsContainer');
  if (!container) return;

  if (data.length === 0) {
    container.innerHTML = '<div class="empty-state"><b>Nenhum membro encontrado</b>Ajuste ou limpe os filtros.</div>';
    return;
  }

  // Agrupar por órgão
  const grupos = {};
  data.forEach(m => { (grupos[m.orgao_grupo] = grupos[m.orgao_grupo] || []).push(m); });

  container.innerHTML = Object.entries(grupos).map(([orgao, membros]) => `
    <div class="org">
      <div><div style="font-weight:600">${escapeHTML(orgao)}</div><div class="hint">${plural(membros.length, 'membro', 'membros')}</div></div>
      <div class="people">${membros.map(m => `
        <div>
          <div>
            <div class="cell-main">${escapeHTML(m.nome)}</div>
            <div class="cell-sub">${escapeHTML(m.cargo)} · ${escapeHTML(m.instituicao)}</div>
            ${cceContact(m)}
          </div>
          <div style="display:flex;gap:6px;flex-wrap:wrap;justify-content:flex-end">
            ${m.destaque ? '<span class="tag ok">Coordenação</span>' : ''}
            <span class="tag ${m.tipo === 'TITULAR' ? 'info' : 'plain'}">${m.tipo === 'TITULAR' ? 'Titular' : 'Suplente'}</span>
          </div>
        </div>`).join('')}
      </div>
    </div>`).join('');
}

function renderCCETable(data) {
  const tbody = document.getElementById('cceTableBody');
  if (!tbody) return;

  if (data.length === 0) {
    tbody.innerHTML = emptyRow(6, 'Nenhum membro encontrado para os filtros selecionados.', '');
    return;
  }

  tbody.innerHTML = data.map(m => {
    const cleanPhone = (m.telefone || '').replace(/\D/g, '').slice(0, 11);
    const resumo = `${m.nome} - ${m.cargo} (${m.orgao_grupo}): ${m.email} / ${m.telefone}`;
    return `<tr>
      <td><div class="cell-main">${escapeHTML(m.nome)}</div><div class="cell-sub">${escapeHTML(m.cargo)}</div></td>
      <td>${escapeHTML(m.orgao_grupo)}<div class="cell-sub">${escapeHTML(m.instituicao)}</div></td>
      <td><span class="tag ${m.tipo === 'TITULAR' ? 'info' : 'plain'}">${m.tipo === 'TITULAR' ? 'Titular' : 'Suplente'}</span>${m.destaque ? ' <span class="tag ok">Coord.</span>' : ''}</td>
      <td><a href="mailto:${escapeHTML(m.email)}" style="text-decoration:none">${escapeHTML(m.email)}</a></td>
      <td style="white-space:nowrap">${escapeHTML(m.telefone)}${cleanPhone ? ` <a href="https://wa.me/55${cleanPhone}" target="_blank" rel="noopener noreferrer" title="WhatsApp"><i class="fab fa-whatsapp"></i></a>` : ''}</td>
      <td class="r"><button class="btn btn-sm" type="button" onclick="navigator.clipboard.writeText(decodeURIComponent('${encodeURIComponent(resumo)}')); showToast('Contato copiado', 'success')">Copiar contato</button></td>
    </tr>`;
  }).join('');
}

function exportarCCECSV() {
  const data = window.currentFilteredCCE || window.cceMembrosData || [];
  if (data.length === 0) {
    if (typeof showAlert === 'function') showAlert('Nenhum dado para exportar.', 'error');
    return;
  }

  const headers = ['Tipo', 'Nome Completo', 'Órgão / Segmento', 'Instituição Representada', 'Cargo / Função', 'E-mail Institucional', 'Telefone'];
  const rows = data.map(m => [
    `"${m.tipo}"`,
    `"${(m.nome || '').replace(/"/g, '""')}"`,
    `"${(m.orgao_grupo || '').replace(/"/g, '""')}"`,
    `"${(m.instituicao || '').replace(/"/g, '""')}"`,
    `"${(m.cargo || '').replace(/"/g, '""')}"`,
    `"${(m.email || '').replace(/"/g, '""')}"`,
    `"${(m.telefone || '').replace(/"/g, '""')}"`
  ]);

  const csvContent = "\uFEFF" + [headers.join(';'), ...rows.map(r => r.join(';'))].join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `membros_cce_ceara_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
