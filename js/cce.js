function exportarCCECSV() {
  const data = window.currentFilteredCCE || window.cceMembrosData || [];
  if (data.length === 0) {
    if (typeof showAlert === 'function') showAlert('Nenhum dado para exportar.', 'error');
    return;
  }

  const headers = ['Tipo', 'Nome Completo', 'Órgão / Segmento', 'Instituição Representada', 'Cargo / Função', 'E-mail Institucional', 'Telefone'];
  const rows = data.map(m => [
    `"${m.tipo}"`,
    `"${(m.nome || '').replace(/"/g, '""')}"`,
    `"${(m.orgao_grupo || '').replace(/"/g, '""')}"`,
    `"${(m.instituicao || '').replace(/"/g, '""')}"`,
    `"${(m.cargo || '').replace(/"/g, '""')}"`,
    `"${(m.email || '').replace(/"/g, '""')}"`,
    `"${(m.telefone || '').replace(/"/g, '""')}"`
  ]);

  const csvContent = "\uFEFF" + [headers.join(';'), ...rows.map(r => r.join(';'))].join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `membros_cce_ceara_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
